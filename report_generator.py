def add_section_heading(doc, text):
	p = doc.add_paragraph()
	r = p.add_run(text)
	r.bold = True
	r.font.size = Pt(16)


def add_bullets(doc, items):
	for item in items:
		doc.add_paragraph(item, style='List Bullet')


